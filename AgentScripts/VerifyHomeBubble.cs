if (!UnityEditor.EditorApplication.isPlaying) throw new System.Exception("Run in Play Mode only");
var ui = UnityEngine.Object.FindFirstObjectByType<HomeDialogueUI>();
var npc = System.Linq.Enumerable.First(UnityEngine.Object.FindObjectsByType<HomeInteractable>(UnityEngine.FindObjectsSortMode.None), i => i.action == HomeInteractable.ActionType.Dialogue);
if (!ui.bubbleTexture) throw new System.Exception("Missing bubble texture");
npc.Interact(ui);
if (!ui.IsOpen) throw new System.Exception("Dialogue did not start");
for (int i = 0; i < npc.lines.Length * 2 + 1 && ui.IsOpen; i++) ui.Advance();
if (ui.IsOpen || !npc.DialogueCompleted || npc.CanInteract) throw new System.Exception("Completion state incorrect");
npc.SetNearby(true, false);
if (npc.floatingIcon.gameObject.activeSelf || npc.promptText.gameObject.activeSelf) throw new System.Exception("Interaction hints visible");
npc.Interact(ui);
if (ui.IsOpen) throw new System.Exception("Completed dialogue reopened");
var bubble = npc.GetComponentInChildren<HomeSpeechBubble>();
if (!bubble) throw new System.Exception("Bubble missing");
var text = bubble.GetComponentInChildren<TMPro.TMP_Text>();
if (text.text != "See you later." || text.font != ui.dialogueText.font) throw new System.Exception("Text/font mismatch");
var initial = bubble.rectTransform.sizeDelta;
text.text = "A longer monologue that wraps onto several lines while keeping its pixel border and tail unchanged.";
bubble.Fit(text);
var larger = bubble.rectTransform.sizeDelta;
if (larger.y <= initial.y) throw new System.Exception("Bubble does not grow with text");
text.text = "See you later.";
bubble.Fit(text);
return new { initial, larger, bubblePosition = bubble.transform.position, text = text.text };
